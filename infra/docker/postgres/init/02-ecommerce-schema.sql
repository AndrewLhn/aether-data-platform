CREATE TABLE public.customers (
  customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  full_name TEXT NOT NULL,
  customer_status TEXT NOT NULL DEFAULT 'active'
    CHECK (customer_status IN ('active', 'suspended')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.orders (
  order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES public.customers (customer_id),
  external_order_reference TEXT NOT NULL UNIQUE,
  order_status TEXT NOT NULL
    CHECK (order_status IN ('created', 'paid', 'cancelled', 'fulfilled')),
  currency CHAR(3) NOT NULL,
  total_amount NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX orders_customer_created_at_idx
  ON public.orders (customer_id, created_at DESC);

CREATE TABLE public.payments (
  payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES public.orders (order_id),
  provider TEXT NOT NULL,
  provider_payment_reference TEXT NOT NULL UNIQUE,
  payment_status TEXT NOT NULL
    CHECK (payment_status IN ('pending', 'authorized', 'captured', 'failed', 'refunded')),
  amount NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
  currency CHAR(3) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX payments_order_created_at_idx
  ON public.payments (order_id, created_at DESC);

CREATE TABLE public.inventory (
  sku TEXT PRIMARY KEY,
  product_name TEXT NOT NULL,
  available_quantity INTEGER NOT NULL CHECK (available_quantity >= 0),
  reserved_quantity INTEGER NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (reserved_quantity <= available_quantity)
);

CREATE PUBLICATION aether_cdc_publication
  FOR TABLE public.customers, public.orders, public.payments, public.inventory;
